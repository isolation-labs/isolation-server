// The Isolation code view (PLAN V1, with the V3 git view folded in) — a first-party
// Monaco editor over the doorman's execd-backed file API. Served at /v/<viewId>/ by
// isolation-server itself: no process in the sandbox, no code-server. Direct links
// carry the location in the QUERY (?file=<workspace-relative-path>&line=<n>) so the
// doorman's routing stays untouched, and a mounted view navigates in place on a
// `isolation:open` postMessage instead of reloading.
//
// The sidebar is a full file explorer: create/rename/duplicate/delete via a context
// menu, drag-and-drop move (plus OS-file drop = upload), download, clipboard-style
// copy/paste, keyboard navigation, and refresh-on-focus. Saves are stale-guarded:
// the server refuses a write when the file moved underneath the editor.
//
// Source control (VS Code-shaped): a collapsible section under the tree lists every
// NESTED repo's working state (the workspace root is the session branch — session
// sync's job, never shown here) with stage/unstage/discard/commit/push/pull/branches;
// tree rows are colored + badged by git status; the file menu grows a Git section; a
// change opens as a Monaco diff tab whose right side is the live, saveable buffer.
// The slim entry (generated by scripts/build-editor.mjs): the full editor + monarch
// syntax highlighting, WITHOUT the worker-backed css/html/json/typescript language
// services — projectless single-file services mark every cross-file import as an
// error and need workers we don't ship.

// A document = one workspace file's Monaco model plus its save bookkeeping. Shared by
// reference between the file's tab and any worktree diff tab, so an edit in one IS the
// edit in the other and saving either saves the buffer.
interface Doc {
  path: string;
  model: monaco.editor.ITextModel;
  savedVersion: number;
  mtime?: number;
}

const docs = new Map<string, Doc>();

// A media file opens as a preview pane, not a Monaco model — Monaco itself is
// text-only. A diff tab holds an `original` model (HEAD or index) against either the
// shared document (worktree diffs) or a read-only `modifiedRO` model (staged diffs,
// deleted files).
type TabKind = "text" | "image" | "video" | "audio" | "diff";


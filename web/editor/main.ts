// Refresh when the tab regains focus (agents/terminals create files while you're away),
// throttled so tab-flipping doesn't hammer the sandbox.
let lastFocusRefresh = 0;
window.addEventListener("focus", () => {
  if (Date.now() - lastFocusRefresh < 5000) return;
  lastFocusRefresh = Date.now();
  void reloadTree();
  void syncDocs();
});

// Keyboard navigation over the visible rows.
treeEl.addEventListener("keydown", (e) => {
  const rows = [...treeEl.querySelectorAll<HTMLElement>(".node")].filter((r) => r.offsetParent !== null);
  const cur = document.activeElement as HTMLElement;
  const i = rows.indexOf(cur);
  const focusRow = (j: number) => rows[Math.max(0, Math.min(rows.length - 1, j))]?.focus();
  if (e.key === "ArrowDown") { e.preventDefault(); focusRow(i + 1); }
  else if (e.key === "ArrowUp") { e.preventDefault(); focusRow(i - 1); }
  else if (e.key === "ArrowRight" && cur?.dataset.dir === "true") { e.preventDefault(); void toggleDir(cur.dataset.path!, true); }
  else if (e.key === "ArrowLeft" && cur?.dataset.path !== undefined) {
    e.preventDefault();
    if (cur.dataset.dir === "true" && dirNodes.get(cur.dataset.path!)?.expanded) void toggleDir(cur.dataset.path!, false);
    else {
      const parent = parentOf(cur.dataset.path!);
      dirNodes.get(parent)?.rowEl?.focus();
    }
  } else if ((e.key === "Enter" || e.key === " ") && cur?.dataset.path !== undefined) {
    e.preventDefault();
    if (cur.dataset.dir === "true") void toggleDir(cur.dataset.path!);
    else void openFile(cur.dataset.path!);
  }
});


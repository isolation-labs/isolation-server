function renderTabs(): void {
  tabsEl.replaceChildren(
    ...[...tabs.values()].map((t) => {
      const el = document.createElement("div");
      el.className = `tab${t === active ? " active" : ""}${isDirty(t) ? " dirty" : ""}`;
      el.setAttribute("role", "tab");
      el.title = t.diff ? `${t.path} — ${t.diff.staged ? "HEAD ↔ index" : "index ↔ working tree"}` : t.path;
      const name = document.createElement("span");
      name.textContent = basename(t.path);
      el.append(name);
      if (t.diff) {
        const suffix = document.createElement("span");
        suffix.className = "suffix";
        suffix.textContent = t.diff.staged ? "(Index)" : "(Working Tree)";
        el.append(suffix);
      }
      const close = document.createElement("button");
      close.className = "close";
      close.title = "Close";
      close.innerHTML = `<span class="x">&times;</span>`;
      close.onclick = (e) => {
        e.stopPropagation();
        closeTab(t);
      };
      el.onclick = () => activate(t);
      el.append(close);
      return el;
    }),
  );
}

function syncUrl(): void {
  const u = new URL(location.href);
  u.searchParams.delete("token"); // promoted to a cookie by the doorman on first load
  u.searchParams.delete("line");
  if (active && !active.diff) u.searchParams.set("file", active.path);
  else u.searchParams.delete("file");
  history.replaceState(null, "", u);
}

const mediaEl = $("media-view");

function renderMedia(t: Tab): void {
  const src = `api/file?path=${encodeURIComponent(t.path)}`;
  const el = t.kind === "image" ? document.createElement("img") : document.createElement(t.kind as "video" | "audio");
  el.setAttribute("src", src);
  if (el instanceof HTMLMediaElement) el.controls = true;
  el.onerror = () => flash(`preview failed to load ${basename(t.path)}`, true);
  mediaEl.replaceChildren(el);
}

function activate(t: Tab): void {
  if (active && active !== t) {
    if (active.kind === "diff") active.viewState = diffEditor.saveViewState();
    else if (active.doc) active.viewState = editor.saveViewState();
  }
  active = t;
  // A successful open supersedes any standing error (errors don't auto-expire).
  if (statusMsg.classList.contains("error")) {
    statusMsg.textContent = "";
    statusMsg.classList.remove("error");
  }
  mediaEl.hidden = true;
  mediaEl.replaceChildren(); // stop any playing video/audio
  diffHost.hidden = true;
  if (t.kind === "diff" && t.original) {
    const modified = t.doc?.model ?? t.modifiedRO!;
    diffHost.hidden = false;
    diffEditor.setModel({ original: t.original, modified });
    diffEditor.updateOptions({ readOnly: !t.doc });
    if (t.viewState) diffEditor.restoreViewState(t.viewState as monaco.editor.IDiffEditorViewState);
    statusLang.textContent = modified.getLanguageId();
  } else if (t.kind === "text" && t.doc) {
    editor.setModel(t.doc.model);
    if (t.viewState) editor.restoreViewState(t.viewState as monaco.editor.ICodeEditorViewState);
    statusLang.textContent = t.doc.model.getLanguageId();
  } else {
    renderMedia(t);
    mediaEl.hidden = false;
    statusLang.textContent = t.kind;
  }
  emptyEl.classList.add("hidden");
  statusPath.textContent = t.diff ? `${t.path}  ·  ${t.diff.staged ? "HEAD ↔ index" : "index ↔ working tree"}` : t.path;
  renderTabs();
  markActiveTreeNode();
  markActiveScmRow();
  syncUrl();
  if (t.kind === "text") editor.focus();
  else if (t.kind === "diff") diffEditor.getModifiedEditor().focus();
}

// Drop a doc once no tab references it.
function releaseDoc(doc: Doc | undefined): void {
  if (!doc) return;
  if ([...tabs.values()].some((t) => t.doc === doc)) return;
  docs.delete(doc.path);
  doc.model.dispose();
}

function closeTab(t: Tab, force = false): void {
  // A shared buffer keeps its edits in the surviving tab — only the LAST tab holding
  // a dirty doc asks.
  const lastHolder = !!t.doc && ![...tabs.values()].some((o) => o !== t && o.doc === t.doc);
  if (!force && lastHolder && isDirty(t) && !confirm(`${t.path} has unsaved changes. Close anyway?`)) return;
  tabs.delete(t.key);
  t.original?.dispose();
  t.modifiedRO?.dispose();
  releaseDoc(t.doc);
  if (active === t) {
    active = [...tabs.values()].pop();
    if (active) activate(active);
    else {
      editor.setModel(null);
      diffEditor.setModel(null);
      diffHost.hidden = true;
      mediaEl.hidden = true;
      mediaEl.replaceChildren();
      emptyEl.classList.remove("hidden");
      statusPath.textContent = "";
      statusLang.textContent = "";
      renderTabs();
      markActiveTreeNode();
      markActiveScmRow();
      syncUrl();
    }
  } else renderTabs();
}

// Load (or reuse) the document for a workspace file. Throws on read failures and on
// binaries — the caller reports.
async function loadDoc(path: string): Promise<Doc> {
  const have = docs.get(path);
  if (have) return have;
  const read = await apiRead(path);
  const head = new Uint8Array(read.bytes.slice(0, 8192));
  if (head.includes(0)) throw new Error(`${basename(path)} looks binary — not opening`);
  const text = new TextDecoder().decode(read.bytes);
  const model = monaco.editor.createModel(text, undefined, monaco.Uri.file(`/${path}`));
  const doc: Doc = { path, model, savedVersion: model.getAlternativeVersionId(), mtime: read.mtime };
  model.onDidChangeContent(() => renderTabs());
  docs.set(path, doc);
  return doc;
}

async function openFile(path: string, line?: number): Promise<void> {
  let t = tabs.get(path);
  const media = mediaKindOf(path);
  if (!t && media) {
    t = { key: path, path, kind: media };
    tabs.set(path, t);
  }
  if (!t) {
    let doc: Doc;
    try {
      doc = await loadDoc(path);
    } catch (e) {
      flash(`open failed: ${(e as Error).message}`, true);
      return;
    }
    t = { key: path, path, kind: "text", doc, viewState: null };
    tabs.set(path, t);
  }
  activate(t);
  void revealInTree(path);
  if (line && line > 0 && t.doc) {
    editor.revealLineInCenter(line);
    editor.setPosition({ lineNumber: line, column: 1 });
  }
}

async function save(): Promise<void> {
  const t = active;
  const d = t?.doc;
  if (!t || !d || !isDirty(t)) return;
  const version = d.model.getAlternativeVersionId();
  try {
    const out = await apiSave(d.path, d.model.getValue(), d.mtime);
    d.savedVersion = version;
    d.mtime = out.mtime;
    warnedStale.delete(d.path);
    renderTabs();
    flash("Saved");
    void refreshGit(true);
  } catch (e) {
    const err = e as Error & { stale?: boolean };
    if (err.stale) {
      // The file moved underneath the editor (agent/terminal). Overwrite or keep the
      // buffer unsaved — reopening the file loads the sandbox version.
      if (confirm(`${d.path} changed in the sandbox since you opened it.\n\nOK overwrites the sandbox version with yours; Cancel keeps your buffer unsaved (close and reopen the file to load the sandbox version).`)) {
        try {
          const out = await apiSave(d.path, d.model.getValue());
          d.savedVersion = version;
          d.mtime = out.mtime;
          renderTabs();
          flash("Saved (overwrote the sandbox version)");
          void refreshGit(true);
        } catch (e2) {
          flash(`save failed: ${(e2 as Error).message}`, true);
        }
      }
      return;
    }
    flash(`save failed: ${err.message}`, true);
  }
}


// --- api ------------------------------------------------------------------------

interface Entry {
  name: string;
  dir: boolean;
}

const errorOf = async (r: Response): Promise<string> => ((await r.json().catch(() => ({}))) as { error?: string }).error ?? `HTTP ${r.status}`;

async function apiList(path: string): Promise<Entry[]> {
  const r = await fetch(`api/list?path=${encodeURIComponent(path)}`);
  if (!r.ok) throw new Error(await errorOf(r));
  return ((await r.json()) as { entries: Entry[] }).entries;
}

async function apiRead(path: string): Promise<{ bytes: ArrayBuffer; mtime?: number }> {
  const r = await fetch(`api/file?path=${encodeURIComponent(path)}`);
  if (!r.ok) throw new Error(await errorOf(r));
  const mtime = Number(r.headers.get("X-Iso-Mtime")) || undefined;
  return { bytes: await r.arrayBuffer(), mtime };
}

// Save with the stale gate; expectMtime undefined = unconditional write.
async function apiSave(path: string, content: string | Blob, expectMtime?: number): Promise<{ mtime?: number }> {
  const r = await fetch(`api/file?path=${encodeURIComponent(path)}`, {
    method: "PUT",
    body: content,
    headers: expectMtime ? { "X-Iso-Expect-Mtime": String(expectMtime) } : {},
  });
  const body = (await r.json().catch(() => ({}))) as { error?: string; stale?: boolean; mtime?: number };
  if (!r.ok) {
    const e = new Error(body.error ?? `HTTP ${r.status}`) as Error & { stale?: boolean };
    e.stale = body.stale;
    throw e;
  }
  return { mtime: body.mtime };
}

// mtimes for a batch of workspace files; 0 = gone. The "did it change under me" probe.
async function apiStat(paths: string[]): Promise<Record<string, number>> {
  const r = await fetch(`api/stat?${paths.map((p) => `path=${encodeURIComponent(p)}`).join("&")}`);
  if (!r.ok) throw new Error(await errorOf(r));
  return ((await r.json()) as { mtimes: Record<string, number> }).mtimes;
}

async function apiOp(op: string, path: string, to?: string): Promise<void> {
  const r = await fetch("api/op", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ op, path, ...(to ? { to } : {}) }),
  });
  if (!r.ok) throw new Error(await errorOf(r));
}


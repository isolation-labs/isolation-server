let repos: RepoStatus[] = [];
const fileGit = new Map<string, FileGit>();
const dirGit = new Map<string, { code: string; rank: number }>();
let ignoredDirs: string[] = []; // workspace paths, no trailing slash
const ignoredFiles = new Set<string>();

const CONFLICT_CODES = new Set(["DD", "AU", "UD", "UA", "DU", "AA", "UU"]);

// The badge letter for a status pair, and how loudly it should color a folder: a
// conflict beats everything; a folder with edits reads "modified" even when a file
// beneath it was deleted (deleted files aren't in the tree to see).
function classify(index: string, work: string): { code: string; rank: number } {
  const xy = `${index}${work}`;
  if (CONFLICT_CODES.has(xy)) return { code: "C", rank: 6 };
  if (xy === "??") return { code: "U", rank: 2 };
  if (index === "A") return work === "D" ? { code: "D", rank: 4 } : { code: "A", rank: 3 };
  if (work === "D" || (index === "D" && work === " ")) return { code: "D", rank: 4 };
  if (work === "M" || index === "M" || work === "T" || index === "T") return { code: "M", rank: 5 };
  if (index === "R" || work === "R" || index === "C" || work === "C") return { code: "R", rank: 3 };
  return { code: "M", rank: 5 };
}

const wsPath = (repo: string, rel: string): string => `${repo}/${rel}`.replace(/\/$/, "");

function rebuildGitMaps(): void {
  fileGit.clear();
  dirGit.clear();
  ignoredFiles.clear();
  const dirs: string[] = [];
  for (const r of repos) {
    for (const f of r.files) {
      const { code, rank } = classify(f.index, f.work);
      const p = wsPath(r.dir, f.path);
      fileGit.set(p, { repo: r.dir, rel: f.path, code, rank, index: f.index, work: f.work, renamedFrom: f.renamedFrom });
      let d = parentOf(p);
      while (d) {
        const cur = dirGit.get(d);
        if (!cur || cur.rank < rank) dirGit.set(d, { code, rank });
        d = parentOf(d);
      }
    }
    for (const ig of r.ignored) {
      if (ig.endsWith("/")) dirs.push(wsPath(r.dir, ig));
      else ignoredFiles.add(wsPath(r.dir, ig));
    }
  }
  ignoredDirs = dirs;
}

const isIgnored = (path: string): boolean => ignoredFiles.has(path) || ignoredDirs.some((d) => path === d || path.startsWith(`${d}/`));

// The repo a workspace path belongs to (longest match), or undefined outside every repo.
function repoOf(path: string): RepoStatus | undefined {
  let best: RepoStatus | undefined;
  for (const r of repos) {
    if ((path === r.dir || path.startsWith(`${r.dir}/`)) && (!best || r.dir.length > best.dir.length)) best = r;
  }
  return best;
}
const relOf = (repo: RepoStatus, path: string): string => (path === repo.dir ? "." : path.slice(repo.dir.length + 1));

function decorateRow(row: HTMLElement, path: string, dir: boolean): void {
  const st = dir ? dirGit.get(path) : fileGit.get(path);
  const badge = row.querySelector<HTMLElement>(".badge");
  if (st) {
    row.dataset.git = st.code;
    if (badge) badge.textContent = dir ? "•" : st.code;
  } else {
    delete row.dataset.git;
    if (badge) badge.textContent = "";
  }
  row.classList.toggle("ignored", !st && isIgnored(path));
}

function decorateTree(): void {
  for (const [p, row] of fileRows) decorateRow(row, p, false);
  for (const [p, n] of dirNodes) if (n.rowEl) decorateRow(n.rowEl, p, true);
}


interface MenuItem {
  label: string;
  danger?: boolean;
  disabled?: boolean;
  checked?: boolean; // radio-style mark (branch pickers)
  indent?: boolean; // align with checked siblings
  onAct: () => void;
}
type MenuEntry = MenuItem | "sep" | { heading: string };

const menuEl = document.createElement("div");
menuEl.id = "ctx-menu";
menuEl.hidden = true;
document.body.append(menuEl);

function closeMenu(): void {
  menuEl.hidden = true;
}
document.addEventListener("click", closeMenu);
document.addEventListener("keydown", (e) => e.key === "Escape" && closeMenu());

function openMenu(x: number, y: number, items: MenuEntry[]): void {
  menuEl.replaceChildren(
    ...items.map((it) => {
      if (it === "sep") {
        const s = document.createElement("div");
        s.className = "sep";
        return s;
      }
      if ("heading" in it) {
        const h = document.createElement("div");
        h.className = "heading";
        h.textContent = it.heading;
        return h;
      }
      const b = document.createElement("button");
      b.textContent = it.label;
      if (it.danger) b.classList.add("danger");
      if (it.checked) b.classList.add("checked");
      if (it.indent) b.classList.add("indent");
      b.disabled = !!it.disabled;
      b.onclick = (e) => {
        e.stopPropagation();
        closeMenu();
        it.onAct();
      };
      return b;
    }),
  );
  menuEl.hidden = false;
  const r = menuEl.getBoundingClientRect();
  menuEl.style.left = `${Math.min(x, innerWidth - r.width - 8)}px`;
  menuEl.style.top = `${Math.max(4, Math.min(y, innerHeight - r.height - 8))}px`;
}

// Anchor a menu under an element (buttons that open menus).
const menuBelow = (el: HTMLElement, items: MenuEntry[]): void => {
  const r = el.getBoundingClientRect();
  openMenu(r.left, r.bottom + 4, items);
};


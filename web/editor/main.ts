// The Isolation code view (PLAN V1) — a first-party Monaco editor over the doorman's
// execd-backed file API. Served at /v/<viewId>/ by isolation-server itself: no process
// in the sandbox, no code-server. Direct links carry the location in the QUERY
// (?file=<workspace-relative-path>&line=<n>) so the doorman's routing stays untouched,
// and a mounted view navigates in place on a `isolation:open` postMessage instead of
// reloading.
//
// The sidebar is a full file explorer: create/rename/duplicate/delete via a context
// menu, drag-and-drop move (plus OS-file drop = upload), download, clipboard-style
// copy/paste, keyboard navigation, and refresh-on-focus. Saves are stale-guarded:
// the server refuses a write when the file moved underneath the editor.
// The slim entry (generated by scripts/build-editor.mjs): the full editor + monarch
// syntax highlighting, WITHOUT the worker-backed css/html/json/typescript language
// services — projectless single-file services mark every cross-file import as an
// error and need workers we don't ship.

menuEl.hidden = true;
document.body.append(menuEl);

function closeMenu(): void {
  menuEl.hidden = true;
}
document.addEventListener("click", closeMenu);
document.addEventListener("keydown", (e) => e.key === "Escape" && closeMenu());

function openMenu(x: number, y: number, items: (MenuItem | "sep")[]): void {
  menuEl.replaceChildren(
    ...items.map((it) => {
      if (it === "sep") {
        const s = document.createElement("div");
        s.className = "sep";
        return s;
      }
      const b = document.createElement("button");
      b.textContent = it.label;
      if (it.danger) b.className = "danger";
      b.onclick = (e) => {
        e.stopPropagation();
        closeMenu();
        it.onAct();
      };
      return b;
    }),
  );
  menuEl.hidden = false;
  const r = menuEl.getBoundingClientRect();
  menuEl.style.left = `${Math.min(x, innerWidth - r.width - 8)}px`;
  menuEl.style.top = `${Math.min(y, innerHeight - r.height - 8)}px`;
}

// clipboard-style copy/paste of tree entries
let clipboard: { path: string; cut: boolean } | undefined;

function fileMenu(path: string): (MenuItem | "sep")[] {
  return [
    { label: "Open", onAct: () => void openFile(path) },
    "sep",
    { label: "Rename…", onAct: () => startInlineRename(path) },
    { label: "Duplicate", onAct: () => void duplicate(path) },
    { label: "Copy", onAct: () => { clipboard = { path, cut: false }; flash(`copied ${basename(path)}`); } },
    { label: "Cut", onAct: () => { clipboard = { path, cut: true }; flash(`cut ${basename(path)}`); } },
    "sep",
    { label: "Download", onAct: () => void download(path) },
    "sep",
    { label: "Delete…", danger: true, onAct: () => void remove(path) },
  ];
}


// The Git section of a row's menu — present for anything inside a repo (VS Code's
// explorer shows "Open Changes" and friends only for repo files); actions that don't
// apply to this row's state stay visible but disabled.
function gitMenuFor(path: string, dir: boolean): MenuEntry[] {
  const repo = repoOf(path);
  if (!repo) return [];
  const rel = relOf(repo, path);
  const isRoot = rel === ".";
  const st = dir ? dirGit.get(path) : fileGit.get(path);
  const f = dir ? undefined : fileGit.get(path);
  const hasWork = !!f && (f.work !== " " || f.index === "?");
  const hasIndex = !!f && f.index !== " " && f.index !== "?";
  // Folders: anything beneath with a worktree change / staged change.
  const under = (pred: (g: FileGit) => boolean) => [...fileGit.values()].some((g) => g.repo === repo.dir && `${repo.dir}/${g.rel}`.startsWith(`${path}/`) && pred(g));
  const dirWork = dir && (isRoot ? repo.files.some((x) => x.work !== " " || x.index === "?") : under((g) => g.work !== " " || g.index === "?"));
  const dirIndex = dir && (isRoot ? repo.files.some((x) => x.index !== " " && x.index !== "?") : under((g) => g.index !== " " && g.index !== "?"));
  const paths = [rel];
  const items: MenuEntry[] = ["sep", { heading: `Git · ${repo.dir}` }];
  if (!dir) {
    items.push(
      { label: "Open Changes", disabled: !hasWork, onAct: () => void openDiff(repo.dir, rel, false) },
      { label: "Open Staged Changes", disabled: !hasIndex, onAct: () => void openDiff(repo.dir, rel, true) },
    );
  }
  items.push(
    { label: dir ? "Stage Changes" : "Stage Changes", disabled: dir ? !dirWork : !hasWork, onAct: () => void gitAction(repo.dir, isRoot ? { op: "stageAll" } : { op: "stage", paths }, "staged") },
    { label: "Unstage Changes", disabled: dir ? !dirIndex : !hasIndex, onAct: () => void gitAction(repo.dir, isRoot ? { op: "unstageAll" } : { op: "unstage", paths: f?.renamedFrom ? [rel, f.renamedFrom] : paths }, "unstaged") },
    {
      label: "Discard Changes…",
      danger: true,
      disabled: dir ? !dirWork : !hasWork,
      onAct: () => void confirmDiscard(repo.dir, isRoot ? undefined : paths, dir ? `everything under ${basename(path)}` : basename(path)),
    },
  );
  void st;
  return items;
}


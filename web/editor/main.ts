// Dirs that are almost never what you're looking for: dimmed and sorted last.
const NOISE_DIRS = new Set(["node_modules", ".git", "dist", "build", "out", ".next", ".venv", "venv", "__pycache__", "target", "vendor", ".cache"]);

// --- file tree ------------------------------------------------------------------
// Registry-backed: every directory (path "" = the root) keeps its container +
// expansion state, so refreshes and deep reveals can rebuild without losing shape.

interface DirNode {
  kidsEl: HTMLElement;
  rowEl?: HTMLElement; // root has no row
  twistEl?: HTMLElement;
  expanded: boolean;
  loaded: boolean;
  depth: number;
  sig?: string; // signature of the rendered listing (diff-based refresh)
}

const dirNodes = new Map<string, DirNode>();
const fileRows = new Map<string, HTMLElement>();

function markActiveTreeNode(): void {
  for (const [p, el] of fileRows) el.classList.toggle("active", p === active?.path);
}

function makeRow(path: string, name: string, dir: boolean, depth: number): HTMLElement {
  const wrap = document.createElement("div");
  const row = document.createElement("div");
  row.className = `node${dir ? " dir" : ""}${dir && NOISE_DIRS.has(name) ? " dim" : ""}`;
  row.style.paddingLeft = `${8 + depth * 12}px`;
  row.setAttribute("role", "treeitem");
  row.tabIndex = -1;
  row.dataset.path = path;
  row.dataset.dir = String(dir);
  const twist = document.createElement("span");
  twist.className = "twist";
  twist.textContent = dir ? "▸" : "";
  const icon = document.createElement("span");
  icon.className = `icon ${dir ? "cat-folder" : `cat-${fileCategory(name)}`}`;
  icon.innerHTML = dir ? ICON_FOLDER : ICON_FILE;
  const label = document.createElement("span");
  label.className = "name";
  label.textContent = name;
  row.append(twist, icon, label);
  wrap.append(row);

  row.oncontextmenu = (e) => {
    e.preventDefault();
    openMenu(e.clientX, e.clientY, dir ? dirMenu(path) : fileMenu(path));
  };
  row.draggable = true;
  row.addEventListener("dragstart", (e) => {
    e.dataTransfer?.setData("application/x-isolation-path", path);
    e.dataTransfer!.effectAllowed = "move";
  });

  if (dir) {
    const kids = document.createElement("div");
    kids.style.display = "none";
    wrap.append(kids);
    dirNodes.set(path, { kidsEl: kids, rowEl: row, twistEl: twist, expanded: false, loaded: false, depth });
    row.onclick = () => void toggleDir(path);
    wireDropTarget(row, path);
  } else {
    fileRows.set(path, row);
    row.onclick = () => void openFile(path);
  }
  return wrap;
}

const sortEntries = (entries: Entry[]): Entry[] =>
  entries.sort((a, b) => {
    if (a.dir !== b.dir) return Number(b.dir) - Number(a.dir);
    const an = a.dir && NOISE_DIRS.has(a.name) ? 1 : 0;
    const bn = b.dir && NOISE_DIRS.has(b.name) ? 1 : 0;
    return an - bn || a.name.localeCompare(b.name);
  });

// Signature of a rendered listing — the diff-based refresh skips the DOM entirely
// when a directory's contents haven't changed.
const sigOf = (entries: Entry[]): string => entries.map((e) => `${e.name}${e.dir ? "/" : ""}`).join("\n");

function renderEntries(path: string, entries: Entry[]): void {
  const node = dirNodes.get(path);
  if (!node) return;
  // Rebuilding this container drops any descendant registry entries.
  for (const p of [...dirNodes.keys()]) if (p !== path && (path === "" || p.startsWith(`${path}/`))) dirNodes.delete(p);
  for (const p of [...fileRows.keys()]) if (path === "" || p.startsWith(`${path}/`)) fileRows.delete(p);
  node.kidsEl.replaceChildren(...entries.map((e) => makeRow(path ? `${path}/${e.name}` : e.name, e.name, e.dir, node.depth + (path === "" ? 0 : 1))));
  if (!entries.length) {
    const note = document.createElement("div");
    note.className = "tree-note";
    note.textContent = "(empty)";
    node.kidsEl.replaceChildren(note);
  }
  node.loaded = true;
  node.sig = sigOf(entries);
  markActiveTreeNode();
}

async function listInto(path: string): Promise<void> {
  const node = dirNodes.get(path);
  if (!node) return;
  try {
    renderEntries(path, sortEntries(await apiList(path)));
  } catch (e) {
    const note = document.createElement("div");
    note.className = "tree-note";
    note.textContent = `listing failed: ${(e as Error).message}`;
    node.kidsEl.replaceChildren(note);
  }
}

async function toggleDir(path: string, force?: boolean): Promise<void> {
  const node = dirNodes.get(path);
  if (!node) return;
  node.expanded = force ?? !node.expanded;
  if (node.twistEl) node.twistEl.textContent = node.expanded ? "▾" : "▸";
  if (node.expanded && !node.loaded) await listInto(path);
  node.kidsEl.style.display = node.expanded ? "" : "none";
}

// Expand every ancestor so `path` is visible; used by deep links and open-file.
async function revealInTree(path: string): Promise<void> {
  const parts = path.split("/");
  let cur = "";
  for (let i = 0; i < parts.length - 1; i++) {
    cur = cur ? `${cur}/${parts[i]}` : parts[i];
    if (!dirNodes.has(cur)) return; // tree disagrees (fresh op, stale list) — refresh will catch up
    await toggleDir(cur, true);
  }
  markActiveTreeNode();
  fileRows.get(path)?.scrollIntoView({ block: "nearest" });
}

// Diff-based refresh: re-list every expanded directory IN PARALLEL, then touch the DOM
// only where a listing actually changed — an unchanged tree refreshes invisibly (no
// collapse/re-expand flicker). A changed directory re-renders and its previously
// expanded descendants that survive are re-expanded. Ops and window focus funnel here.
let reloading = false;
let rerunWanted = false;
async function reloadTree(): Promise<void> {
  // A refresh requested while one is in flight runs AFTER it, not never — dropping it
  // made a post-op refresh silently miss changes when it raced the focus refresh.
  if (reloading) {
    rerunWanted = true;
    return;
  }
  reloading = true;
  try {
    const targets = [...dirNodes.entries()].filter(([, n]) => n.expanded && n.loaded).map(([p]) => p).sort();
    const fetched = await Promise.all(
      targets.map(async (p) => {
        try {
          return { p, entries: sortEntries(await apiList(p)) };
        } catch {
          return { p, entries: undefined }; // vanished or unreadable — a parent's re-render handles it
        }
      }),
    );
    for (const { p, entries } of fetched) {
      const node = dirNodes.get(p); // a parent's re-render may have replaced or dropped this dir
      if (!node || !entries || (node.loaded && node.sig === sigOf(entries))) continue;
      const expandedDesc = [...dirNodes.entries()]
        .filter(([q, n]) => q !== p && n.expanded && (p === "" || q.startsWith(`${p}/`)))
        .map(([q]) => q)
        .sort();
      renderEntries(p, entries);
      for (const q of expandedDesc) {
        if (dirNodes.has(q)) await toggleDir(q, true);
      }
    }
  } finally {
    reloading = false;
    if (rerunWanted) {
      rerunWanted = false;
      void reloadTree();
    }
  }
}

// Root registry entry: the tree element itself is the root's container.
dirNodes.set("", { kidsEl: treeEl, expanded: true, loaded: false, depth: 0 });


// Inline input row for create/rename — Enter commits, Esc/blur cancels.
function inlineInput(container: HTMLElement, depth: number, initial: string, commit: (name: string) => void): void {
  const row = document.createElement("div");
  row.className = "node";
  row.style.paddingLeft = `${8 + depth * 12}px`;
  const input = document.createElement("input");
  input.className = "inline-input";
  input.value = initial;
  row.append(document.createElement("span"), input);
  (row.firstChild as HTMLElement).className = "twist";
  container.prepend(row);
  input.focus();
  const dot = initial.lastIndexOf(".");
  input.setSelectionRange(0, dot > 0 ? dot : initial.length);
  let done = false;
  const finish = (val?: string) => {
    if (done) return;
    done = true;
    row.remove();
    const name = val?.trim();
    if (name && !name.includes("/") && name !== "." && name !== "..") commit(name);
  };
  input.onkeydown = (e) => {
    e.stopPropagation();
    if (e.key === "Enter") finish(input.value);
    else if (e.key === "Escape") finish();
  };
  input.onblur = () => finish();
}

function startInlineCreate(dirPath: string, isDir: boolean): void {
  void toggleDir(dirPath || "", true).then(() => {
    const node = dirNodes.get(dirPath);
    if (!node) return;
    inlineInput(node.kidsEl, node.depth + (dirPath === "" ? 0 : 1), "", (name) => {
      const path = dirPath ? `${dirPath}/${name}` : name;
      void apiOp(isDir ? "mkdir" : "create", path)
        .then(async () => {
          await reloadTree();
          await toggleDir(dirPath || "", true);
          if (!isDir) await openFile(path);
        })
        .catch((e) => flash(`${isDir ? "folder" : "file"} not created: ${(e as Error).message}`, true));
    });
  });
}

function startInlineRename(path: string): void {
  const isDir = dirNodes.has(path);
  const row = isDir ? dirNodes.get(path)?.rowEl : fileRows.get(path);
  const wrap = row?.parentElement;
  if (!row || !wrap) return;
  const depth = parseInt(row.style.paddingLeft) ? (parseInt(row.style.paddingLeft) - 8) / 12 : 0;
  row.style.display = "none";
  inlineInput(wrap, depth, basename(path), (name) => {
    row.style.display = "";
    if (name === basename(path)) return;
    const to = parentOf(path) ? `${parentOf(path)}/${name}` : name;
    void apiOp("rename", path, to)
      .then(async () => {
        if (isDir) retargetTabsUnder(path, to);
        else retargetTab(path, to);
        await reloadTree();
      })
      .catch((e) => flash(`rename failed: ${(e as Error).message}`, true));
  });
  // blur-cancel must unhide the original row
  const input = wrap.querySelector<HTMLInputElement>(".inline-input");
  input?.addEventListener("blur", () => (row.style.display = ""));
}

async function duplicate(path: string): Promise<void> {
  const name = basename(path);
  const dot = name.lastIndexOf(".");
  const stem = dot > 0 ? name.slice(0, dot) : name;
  const ext = dot > 0 ? name.slice(dot) : "";
  const dir = parentOf(path);
  for (let i = 1; i <= 9; i++) {
    const candidate = `${stem} copy${i > 1 ? ` ${i}` : ""}${ext}`;
    const to = dir ? `${dir}/${candidate}` : candidate;
    try {
      await apiOp("copy", path, to);
      await reloadTree();
      return;
    } catch (e) {
      if (!/exists/.test((e as Error).message)) {
        flash(`duplicate failed: ${(e as Error).message}`, true);
        return;
      }
    }
  }
  flash("duplicate failed: too many copies", true);
}

async function paste(dirPath: string): Promise<void> {
  if (!clipboard) return;
  const to = dirPath ? `${dirPath}/${basename(clipboard.path)}` : basename(clipboard.path);
  if (to === clipboard.path) return flash("already here", true);
  try {
    await apiOp(clipboard.cut ? "rename" : "copy", clipboard.path, to);
    if (clipboard.cut) {
      if (dirNodes.has(clipboard.path)) retargetTabsUnder(clipboard.path, to);
      else retargetTab(clipboard.path, to);
      clipboard = undefined;
    }
    await reloadTree();
  } catch (e) {
    flash(`paste failed: ${(e as Error).message}`, true);
  }
}

async function remove(path: string): Promise<void> {
  const isDir = dirNodes.has(path);
  if (!confirm(`Delete ${isDir ? "folder" : "file"} "${path}"${isDir ? " and everything in it" : ""}? This can't be undone.`)) return;
  try {
    await apiOp("delete", path);
    dropTabsUnder(path);
    await reloadTree();
    flash(`deleted ${basename(path)}`);
  } catch (e) {
    flash(`delete failed: ${(e as Error).message}`, true);
  }
}

async function download(path: string): Promise<void> {
  try {
    const { bytes } = await apiRead(path);
    const a = document.createElement("a");
    a.href = URL.createObjectURL(new Blob([bytes]));
    a.download = basename(path);
    a.click();
    URL.revokeObjectURL(a.href);
  } catch (e) {
    flash(`download failed: ${(e as Error).message}`, true);
  }
}


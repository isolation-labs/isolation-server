async function apiGitShow(repo: string, rel: string, rev: "head" | "index"): Promise<{ content: string | null; binary?: boolean }> {
  const r = await fetch(`api/git/show?repo=${encodeURIComponent(repo)}&path=${encodeURIComponent(rel)}&rev=${rev}`);
  if (!r.ok) throw new Error(await errorOf(r));
  return (await r.json()) as { content: string | null; binary?: boolean };
}

async function apiGitBranches(repo: string): Promise<{ current: string; local: string[]; remote: string[] }> {
  const r = await fetch(`api/git/branches?repo=${encodeURIComponent(repo)}`);
  if (!r.ok) throw new Error(await errorOf(r));
  return (await r.json()) as { current: string; local: string[]; remote: string[] };
}

async function apiGitOp(repo: string, body: Record<string, unknown>): Promise<string> {
  const r = await fetch("api/git/op", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ repo, ...body }),
  });
  const out = (await r.json().catch(() => ({}))) as { error?: string; output?: string };
  if (!r.ok) throw new Error(out.error ?? `HTTP ${r.status}`);
  return out.output ?? "";
}


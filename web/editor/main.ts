// Internal drag = move; a drop carrying OS files = upload into that directory.

function wireDropTarget(el: HTMLElement, dirPath: string): void {
  el.addEventListener("dragover", (e) => {
    e.preventDefault();
    e.stopPropagation();
    el.classList.add("drop-target");
  });
  el.addEventListener("dragleave", () => el.classList.remove("drop-target"));
  el.addEventListener("drop", (e) => {
    e.preventDefault();
    e.stopPropagation();
    el.classList.remove("drop-target");
    void handleDrop(e, dirPath);
  });
}

async function handleDrop(e: DragEvent, dirPath: string): Promise<void> {
  const internal = e.dataTransfer?.getData("application/x-isolation-path");
  if (internal) {
    if (internal === dirPath || dirPath.startsWith(`${internal}/`)) return flash("can't move a folder into itself", true);
    if (parentOf(internal) === dirPath) return;
    const to = dirPath ? `${dirPath}/${basename(internal)}` : basename(internal);
    try {
      await apiOp("rename", internal, to);
      if (dirNodes.has(internal)) retargetTabsUnder(internal, to);
      else retargetTab(internal, to);
      await reloadTree();
      flash(`moved to ${dirPath || "workspace root"}`);
    } catch (err) {
      flash(`move failed: ${(err as Error).message}`, true);
    }
    return;
  }
  if (e.dataTransfer?.files.length) await uploadFiles(dirPath, e.dataTransfer.files);
}


// Open buffers follow the sandbox: agents, terminals and git rewrite files behind the
// editor's back, and the tab must show what's on disk. Clean buffers reload in place
// (an edit, not setValue — cursor, scroll and undo survive); a dirty buffer keeps the
// user's edits and says so once — the stale-save gate decides at save time.
let syncingDocs = false;
const warnedStale = new Set<string>();
async function syncDocs(): Promise<void> {
  if (syncingDocs || !docs.size) return;
  syncingDocs = true;
  try {
    const paths = [...docs.keys()].slice(0, 200);
    const mtimes = await apiStat(paths);
    await Promise.all(
      paths.map(async (path) => {
        const d = docs.get(path);
        const m = mtimes[path];
        if (!d || !m || !d.mtime || m === d.mtime) return;
        if (d.model.getAlternativeVersionId() !== d.savedVersion) {
          if (!warnedStale.has(path)) {
            warnedStale.add(path);
            flash(`${basename(path)} changed in the sandbox — your unsaved edits are kept`, true);
          }
          return;
        }
        const read = await apiRead(path);
        const text = new TextDecoder().decode(read.bytes);
        if (text !== d.model.getValue()) {
          d.model.applyEdits([{ range: d.model.getFullModelRange(), text }]);
          if (active?.doc === d) flash(`${basename(path)} reloaded from the sandbox`);
        }
        d.savedVersion = d.model.getAlternativeVersionId();
        d.mtime = read.mtime ?? m;
        warnedStale.delete(path);
      }),
    );
    renderTabs();
  } catch {
    /* next tick retries */
  } finally {
    syncingDocs = false;
  }
}

// Tab bookkeeping when tree operations move things underneath the editor. A Monaco
// model's URI is fixed, so a rename rebuilds the document; diff tabs on the old path
// are simply closed (their git identity moved with the file).
function retargetTab(oldPath: string, newPath: string): void {
  for (const dt of [...tabs.values()]) if (dt.diff && dt.path === oldPath) closeTab(dt, true);
  const t = tabs.get(oldPath);
  if (!t) return;
  tabs.delete(oldPath);
  if (!t.doc) {
    // media preview: re-key and re-point the preview at the new path
    t.path = newPath;
    t.key = newPath;
    tabs.set(newPath, t);
    if (active === t) activate(t);
    else renderTabs();
    return;
  }
  const wasDirty = isDirty(t);
  const wasActive = active === t;
  const value = t.doc.model.getValue();
  const state = wasActive ? editor.saveViewState() : t.viewState;
  const oldDoc = t.doc;
  const model = monaco.editor.createModel(value, undefined, monaco.Uri.file(`/${newPath}`));
  const doc: Doc = { path: newPath, model, savedVersion: wasDirty ? -1 : model.getAlternativeVersionId(), mtime: oldDoc.mtime };
  model.onDidChangeContent(() => renderTabs());
  docs.set(newPath, doc);
  const nt: Tab = { key: newPath, path: newPath, kind: "text", doc, viewState: state };
  tabs.set(newPath, nt);
  releaseDoc(oldDoc);
  if (wasActive) activate(nt);
  else renderTabs();
}

function dropTabsUnder(path: string): void {
  for (const t of [...tabs.values()]) {
    if (t.path === path || t.path.startsWith(`${path}/`)) closeTab(t, true);
  }
}

function retargetTabsUnder(oldDir: string, newDir: string): void {
  for (const t of [...tabs.values()]) {
    if (t.path.startsWith(`${oldDir}/`)) retargetTab(t.path, `${newDir}${t.path.slice(oldDir.length)}`);
  }
}


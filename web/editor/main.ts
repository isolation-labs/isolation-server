function renderRepo(r: RepoStatus): void {
  let ui = repoUis.get(r.dir);
  if (!ui) {
    ui = buildRepoUi(r.dir);
    repoUis.set(r.dir, ui);
  }
  ui.name.textContent = r.dir;
  ui.name.title = r.remote ? `/workspace/${r.dir} — ${r.remote}` : `/workspace/${r.dir}`;
  ui.branchLabel.textContent = r.detached ? "detached" : r.branch || "no branch";
  ui.ab.textContent = [r.ahead ? `↑${r.ahead}` : "", r.behind ? `↓${r.behind}` : ""].filter(Boolean).join(" ");
  ui.ab.title = r.upstream ? `${r.ahead} to push · ${r.behind} to pull` : "no upstream — Push publishes the branch";
  ui.msg.placeholder = `Message (${navigator.platform.includes("Mac") ? "⌘" : "Ctrl+"}Enter to commit on "${r.branch || "HEAD"}")`;
  if (r.error) ui.error.textContent = r.error;
  const staged = r.files.filter(stagedHalf);
  const changed = r.files.filter(workHalf);
  ui.stagedHead.querySelector(".n")!.textContent = staged.length ? String(staged.length) : "";
  ui.changesHead.querySelector(".n")!.textContent = changed.length ? String(changed.length) : "";
  ui.stagedGroup.hidden = !staged.length;
  ui.stagedList.replaceChildren(...staged.map((f) => scmRow(r, f, true)));
  ui.changesList.replaceChildren(...changed.map((f) => scmRow(r, f, false)));
  ui.changesGroup.hidden = !changed.length && !!staged.length;
  ui.note.textContent = r.files.length ? "" : r.error ? "" : "No changes";
  ui.note.hidden = !!r.files.length;
  (ui as RepoUi & { updateCommitBtn: () => void }).updateCommitBtn();
}

function renderScm(): void {
  scmEl.hidden = !repos.length;
  if (!repos.length) return;
  const total = repos.reduce((n, r) => n + r.files.length, 0);
  scmCount.textContent = total ? String(total) : "";
  for (const r of repos) {
    const sig = JSON.stringify([r.branch, r.detached, r.upstream, r.ahead, r.behind, r.files, r.error]);
    const ui = repoUis.get(r.dir);
    if (ui && ui.sig === sig && ui.root.isConnected) continue;
    renderRepo(r);
    repoUis.get(r.dir)!.sig = sig;
  }
  // Order + prune.
  const keep = new Set(repos.map((r) => r.dir));
  for (const [dir, ui] of repoUis) {
    if (!keep.has(dir)) {
      ui.root.remove();
      repoUis.delete(dir);
    }
  }
  const ordered = repos.map((r) => repoUis.get(r.dir)!.root);
  if (ordered.some((el, i) => scmBody.children[i] !== el)) scmBody.replaceChildren(...ordered);
  markActiveScmRow();
}

let gitRefreshing = false;
let gitRerun = false;
async function refreshGit(force = false): Promise<void> {
  if (gitRefreshing) {
    gitRerun = gitRerun || force;
    return;
  }
  gitRefreshing = true;
  try {
    repos = await apiGitStatus();
    rebuildGitMaps();
    // Which files' git state moved since the last tick → refresh their diff tabs.
    const next = new Map<string, string>();
    for (const [p, g] of fileGit) next.set(p, `${g.index}${g.work}`);
    const changed = new Set<string>();
    for (const [p, s] of next) if (gitSigs.get(p) !== s) changed.add(p);
    for (const p of gitSigs.keys()) if (!next.has(p)) changed.add(p);
    gitSigs = next;
    renderScm();
    decorateTree();
    if (changed.size) void refreshDiffTabs(changed);
  } catch (e) {
    // The section keeps its last state; the status bar carries the error once.
    if (force) flash(`git: ${(e as Error).message}`, true);
  } finally {
    gitRefreshing = false;
    if (gitRerun) {
      gitRerun = false;
      void refreshGit(true);
    }
  }
}

// One git operation with the repo's busy state, then a refresh. `label` is the
// past-tense status-bar word. Worktree-changing ops reload clean buffers.
async function gitAction(repo: string, body: Record<string, unknown>, label: string): Promise<void> {
  const ui = repoUis.get(repo);
  const verb = String(body.op);
  if (ui?.busyLabel) return flash(`${repo}: still ${ui.busyLabel}`, true);
  if (ui) {
    ui.busyLabel = `${verb}…`;
    ui.busy.textContent = ui.busyLabel;
    ui.error.textContent = "";
    ui.root.querySelectorAll("button").forEach((b) => (b.disabled = true));
  }
  try {
    const out = await apiGitOp(repo, body);
    flash(`${repo}: ${label}${out && /push|pull|fetch/.test(verb) ? ` — ${out.split("\n").pop()}` : ""}`);
    return;
  } catch (e) {
    const m = (e as Error).message;
    if (ui) ui.error.textContent = m;
    flash(`${repo}: ${verb} failed`, true);
    throw e;
  } finally {
    if (ui) {
      ui.busyLabel = undefined;
      ui.busy.textContent = "";
      ui.root.querySelectorAll("button").forEach((b) => (b.disabled = false));
      ui.sig = ""; // force a re-render on the next status
    }
    if (/discard|checkout|createBranch|pull/.test(verb)) {
      await reloadTree();
      await syncDocs();
    }
    await refreshGit(true);
  }
}

async function confirmDiscard(repo: string, paths: string[] | undefined, what: string): Promise<void> {
  const msg = paths
    ? `Discard changes to ${what}?\n\nModified files go back to the index; untracked files are DELETED. This can't be undone.`
    : `Discard ALL changes in ${repo}?\n\nEvery modified file goes back to the index and every untracked file is DELETED. This can't be undone.`;
  if (!confirm(msg)) return;
  await gitAction(repo, paths ? { op: "discard", paths } : { op: "discardAll" }, `discarded ${what}`).catch(() => undefined);
}

async function commit(repo: string, o: { amend?: boolean; all?: boolean; push?: boolean }): Promise<void> {
  const ui = repoUis.get(repo);
  const r = repos.find((x) => x.dir === repo);
  if (!ui || !r) return;
  const message = ui.msg.value.trim();
  if (!message) {
    ui.msg.focus();
    ui.error.textContent = "A commit message is required.";
    return;
  }
  const staged = r.files.filter(stagedHalf);
  let all = !!o.all;
  if (!staged.length && !all) {
    if (!r.files.length) return;
    // VS Code's smart commit: nothing staged → offer to commit everything.
    if (!confirm("There are no staged changes to commit.\n\nStage all changes and commit them?")) return;
    all = true;
  }
  try {
    if (all) await gitAction(repo, { op: "stageAll" }, "staged all");
    await gitAction(repo, { op: "commit", message, amend: !!o.amend }, o.amend ? "amended" : "committed");
    ui.msg.value = "";
    if (o.push) await gitAction(repo, { op: "push" }, "pushed");
  } catch {
    /* surfaced in the repo's error line */
  }
}

// The web page for a remote, from whatever form git holds it in: scp-like ssh
// (git@host:o/r.git), ssh://, https with credentials, and the Credential Vault's
// gateway rewrite (https://<gateway>/git/<host>/<o>/<r>) all resolve to https://host/o/r.
function browseUrl(remote: string | undefined): string | undefined {
  if (!remote) return undefined;
  let u: URL | undefined;
  const scp = /^(?:[\w.-]+@)?([\w.-]+):(?!\/\/)(.+)$/.exec(remote);
  if (scp) u = new URL(`https://${scp[1]}/${scp[2]}`);
  else {
    try {
      u = new URL(remote);
    } catch {
      return undefined;
    }
    if (u.protocol === "ssh:" || u.protocol === "git:") u = new URL(`https://${u.hostname}${u.pathname}`);
    else if (u.protocol !== "https:" && u.protocol !== "http:") return undefined;
    const gw = /^\/git\/([\w.-]+)\/(.+)$/.exec(u.pathname);
    if (gw) u = new URL(`https://${gw[1]}/${gw[2]}`);
  }
  u.username = "";
  u.password = "";
  u.search = "";
  u.hash = "";
  u.pathname = u.pathname.replace(/\.git\/?$/, "").replace(/\/$/, "");
  return u.pathname.length > 1 ? u.toString() : undefined;
}

function openExternal(url: string): void {
  // An anchor click, not window.open: works from inside the SPA's iframe and never
  // hands the opener to the remote host.
  const a = document.createElement("a");
  a.href = url;
  a.target = "_blank";
  a.rel = "noopener noreferrer";
  a.click();
}

